#!/usr/bin/env python3
"""Why BLT is weakest on S-NIAH-1: patch statistics, needle-depth breakdown and a worked example.

S-NIAH-1's haystack repeats one short noise passage ("The grass is green. ..."). BLT's entropy model
(512-byte window) predicts it almost perfectly, so its patcher (released threshold, no max patch length)
merges hundreds to thousands of bytes into one patch. This script quantifies that against BPEByte on the
same prompts and writes the appendix material (every number generated, none transcribed):

  table_appendix/blt_sniah_patches.tex   per task x cell: patches/input, median & max patch length,
                                         share of bytes in patches > 64 B, accuracy (BLT vs BPEByte)
  table_appendix/blt_sniah_depth.tex     S-NIAH-1 accuracy by needle depth; max_patch_length=32 ablation
  figure_appendix/blt_sniah_example.tex  one failing S-NIAH-1 item, BLT vs BPEByte patch starts

Inputs:
  reports/niah/sniah123_n250_le4096_pairs.jsonl (2k cell), sniah123_n250_fit4k_pairs.jsonl (4k cell)
  BLT per-item S-NIAH: reports/ext_ci/blt_official/sniah.json (2k) and reports/niah/fit4k/blt_t1335.json (4k)
  BPEByte per-item: reports/niah/fit4k/bpebyte_items.json if present (else accuracy column from trio.jsonl)
  cap ablation: runs/ext_ci_snu55/out/maxpatch_sniah1_fit4k.json ({"None": {cell: acc}, "32": {...}})
                per item (2k, 4k): runs/ext_ci_snu55/out/maxpatch_sniah1_items.json ({"per_item": {"32": {cell: [0/1]}}})
BLT patches: HF entropy model with the 512-byte window (= official to 0.3%; scripts/probes/patch_stats).

  source scripts/probes/patch_stats/env.sh
  CUDA_VISIBLE_DEVICES=2 lingua/.venv/bin/python scripts/probes/ext_ci/blt_sniah_analysis.py
  python scripts/probes/ext_ci/blt_sniah_analysis.py --depth-only     # blt_sniah_depth.tex alone, no patcher
"""
import argparse, json, statistics as st, sys
from collections import defaultdict
from pathlib import Path

L = Path("/mnt/ssd2/hyun2/AUNet")
OVL = L / "paper_overleaf"
sys.path.insert(0, str(L / "scripts/probes/patch_stats"))
sys.path.insert(0, str(L / "scripts/probes"))

GEN = "% GENERATED by AUNet/scripts/probes/ext_ci/blt_sniah_analysis.py — edit the script, not this file."
CELLS = {"2k": ("reports/niah/sniah123_n250_le4096_pairs.jsonl", "2048", "reports/ext_ci/blt_official/sniah.json"),
         "4k": ("reports/niah/sniah123_n250_fit4k_pairs.jsonl", "4096", "reports/niah/fit4k/blt_t1335.json")}
LONG = 64
EXAMPLE_CELL = "4k"   # 2026-10-13: the worked example is a 4k item, as the rest of app:blt_sniah (was 2k)


def needle_bin(q):
    """Fifth of the prompt (0: start, 4: next to the question) that holds the needle value."""
    p = q["prompt"].encode()
    return min(4, int(p.find(q["values"][0].encode()) / len(p) * 5))


def depth_counts(per_item):
    """{(cell name, depth bin): [correct, n]} for S-NIAH-1 from per-item results keyed by cell."""
    depth = defaultdict(lambda: [0, 0])
    for cname, (pairs, L_, _res) in CELLS.items():
        cell = "sniah1/" + L_
        qs = [q for q in map(json.loads, open(L / pairs)) if q["cell"] == cell]
        assert len(qs) == len(per_item[cell]), (cell, len(qs), len(per_item[cell]))
        for q, ok in zip(qs, per_item[cell]):
            depth[(cname, needle_bin(q))][0] += ok; depth[(cname, needle_bin(q))][1] += 1
    return depth


def blt_lengths(patcher, thr, text):
    from measure_blt import entropies, byte_starts, BOS, OFFSET
    from patch_common import lengths_from_starts
    b = text.encode()
    e = entropies(patcher, [[BOS] + [x + OFFSET for x in b]], window=512)[0]
    return lengths_from_starts(byte_starts(e, len(b), thr), len(b)), sorted(set(byte_starts(e, len(b), thr)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--example-only", action="store_true",
                    help="only rewrite figure_appendix/blt_sniah_example.tex (patches a single item; BLT_DEVICE=cpu is enough)")
    ap.add_argument("--depth-only", action="store_true",
                    help="only rewrite table_appendix/blt_sniah_depth.tex from the per-item results (no patcher, no GPU)")
    a = ap.parse_args()
    if a.depth_only:
        write_depth_table(depth_counts({"sniah1/" + L_: json.load(open(L / res))["per_item"]["sniah1/" + L_]
                                        for _pairs, L_, res in CELLS.values()}))
        return
    import torch
    from measure_blt import load_patcher
    from patch_common import lengths_from_starts
    from compression_stability import build_parser
    patcher, thr = load_patcher(torch.float32)
    bpe = build_parser("bpebyte")
    rows, depth, example = [], defaultdict(lambda: [0, 0]), None
    for cname, (pairs, L_, blt_res) in CELLS.items():
        P = [json.loads(l) for l in open(L / pairs)]
        res = json.load(open(L / blt_res))["per_item"]
        idx = defaultdict(int)
        acc = defaultdict(list); stats = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
        for q in P:
            cell = q["cell"]
            if not cell.endswith("/" + L_):
                continue
            ok = res[cell][idx[cell]]; idx[cell] += 1
            task = cell.split("/")[0]
            text = q["prompt"] + " " + q["values"][0]
            n = len(text.encode())
            if a.example_only:
                d = q["prompt"].encode().find(q["values"][0].encode()) / len(q["prompt"].encode())
                if cname == EXAMPLE_CELL and task == "sniah1" and not ok and example is None and d < 0.3:
                    example = (q, text, blt_lengths(patcher, thr, text)[1], sorted(set(bpe(text))))
                continue
            bl, bstarts = blt_lengths(patcher, thr, text)
            pl = lengths_from_starts(bpe(text), n)
            for model, lens in (("BLT", bl), ("BPEByte", pl)):
                s = stats[task][model]
                s["n_patches"].append(len(lens)); s["median"].append(st.median(lens)); s["max"].append(max(lens))
                s["long_share"].append(sum(x for x in lens if x > LONG) / n)
            acc[task].append(ok)
            if task == "sniah1":
                d = q["prompt"].encode().find(q["values"][0].encode()) / len(q["prompt"].encode())
                depth[(cname, needle_bin(q))][0] += ok; depth[(cname, needle_bin(q))][1] += 1
                if cname == EXAMPLE_CELL and not ok and example is None and d < 0.3:
                    example = (q, text, bstarts, sorted(set(bpe(text))))
        for task in () if a.example_only else ("sniah1", "sniah2", "sniah3"):
            for model in ("BLT", "BPEByte"):
                s = stats[task][model]
                rows.append((task, cname, model, st.mean(s["n_patches"]), st.median(s["median"]),
                             st.median(s["max"]), max(s["max"]), 100 * st.mean(s["long_share"]),
                             st.mean(acc[task]) if model == "BLT" else None))
    write_example(example)
    if a.example_only:
        return
    write_patch_table(rows)
    write_depth_table(depth)
    json.dump({"rows": rows, "depth": {f"{k[0]}|{k[1]}": v for k, v in depth.items()}},
              open(L / "reports/blt_t1609/blt_sniah_analysis.json", "w"), indent=1)
    for r in rows:
        print(r)


def write_patch_table(rows):
    TN = {"sniah1": "S-NIAH-1 (repeated noise)", "sniah2": "S-NIAH-2 (essay)", "sniah3": "S-NIAH-3 (essay, UUID)"}
    out = [GEN, r"\begin{table}[t]", r"\centering",
           r"\caption{\hyun{Patch structure of BLT and BPEByte on the 2k and 4k S-NIAH prompts. \emph{Max (med.)} and \emph{Max} are the median and overall longest patch in bytes, and \emph{$>$64\,B} the share of input bytes in patches longer than $64$ bytes.}}", r"\label{tab:blt_sniah_patches}",
           r"\small", r"\setlength{\tabcolsep}{3.5pt}", r"\fitcolumn{%",
           r"\begin{tabular}{lllrrrrr}", r"\toprule",
           r"\textbf{Task} & \textbf{Len.} & \textbf{Parser} & \textbf{Patches} & \textbf{Median} & "
           r"\textbf{Max (med.)} & \textbf{Max} & \textbf{$>$64\,B (\%)} \\", r"\midrule"]
    last = None
    for task, cname, model, npat, med, mx_med, mx, share, _acc in rows:
        if last and task != last:
            out.append(r"\midrule")
        lead = TN[task] if task != last else ""
        last = task
        out.append(f"{lead} & {cname} & {model} & {npat:.0f} & {med:.0f} & {mx_med:.0f} & {mx} & {share:.2f} \\\\")
    out += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table}", ""]
    (OVL / "table_appendix/blt_sniah_patches.tex").write_text("\n".join(out))


def write_depth_table(depth):
    cap = L / "runs/ext_ci_snu55/out/maxpatch_sniah1_fit4k.json"
    capd = json.load(open(cap)) if cap.exists() else None
    items = L / "runs/ext_ci_snu55/out/maxpatch_sniah1_items.json"
    cap_depth = depth_counts(json.load(open(items))["per_item"]["32"]) if items.exists() else None
    out = [GEN, r"\begin{table}[t]", r"\centering",
           r"\caption{\textbf{BLT exact recall (\%) on S-NIAH-1 by needle depth, and with its patches capped at $32$ bytes.}}", r"\label{tab:blt_sniah_depth}",
           r"\small", r"\setlength{\tabcolsep}{4pt}", r"\fitcolumn{%",
           # equal-width value columns: the spanning panel titles would otherwise widen the last column only
           r"\begin{tabular}{l*{5}{>{\centering\arraybackslash}p{1.25cm}}}", r"\toprule",
           r"\multicolumn{6}{l}{\emph{By needle depth} ($0\%$: start of the prompt, $100\%$: question)} \\",
           r" & 0--20\% & 20--40\% & 40--60\% & 60--80\% & 80--100\% \\", r"\cmidrule(lr){2-6}"]
    for cname in ("2k", "4k"):
        for lab, dd in (("no cap (released)", depth), ("cap $32$ bytes", cap_depth)):
            if dd is None:
                continue
            cells = [f"{cname} context, {lab}"]
            for b in range(5):
                k, n = dd.get((cname, b), [0, 0])
                cells.append(f"{100 * k / n:.1f}" if n else "--")
            if dd is cap_depth:   # rows added 2026-10-13, marked as new text
                cells = [rf"\hyun{{{c}}}" for c in cells]
            out.append(" & ".join(cells) + r" \\")
    if capd:
        out += [r"\midrule",
                r"\multicolumn{6}{l}{\emph{By context length} (released patcher vs.\ $32$-byte cap)} \\",
                r" & 0.5k & 1k & 2k & 4k & \\", r"\cmidrule(lr){2-5}"]
        for key, lab in (("None", "no cap (released)"), ("32", "cap $32$ bytes")):
            d = capd[key]
            vals = [d.get(f"sniah1/{x}") for x in (512, 1024, 2048, 4096)]
            out.append(f"{lab} & " + " & ".join("--" if v is None else f"{100 * v:.1f}" for v in vals) + r" & \\")
    out += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table}", ""]
    (OVL / "table_appendix/blt_sniah_depth.tex").write_text("\n".join(out))


def esc(ch):
    return {" ": r"\textvisiblespace{}", "{": r"\{", "}": r"\}", "\\": r"\textbackslash{}", "_": r"\_", "%": r"\%",
            "$": r"\$", "&": r"\&", "#": r"\#", "^": r"\^{}", "~": r"\~{}", "\n": r"\textbackslash{}n"}.get(ch, ch)


def render_span(b, starts, lo, hi):
    s = set(starts)
    return r"\allowbreak{}".join((f"\\bb{{{esc(chr(c))}}}" if i in s else esc(chr(c))) for i, c in
                                 zip(range(lo, hi), b[lo:hi]))


def window_render(text, starts, needle_pos, ctx=60):
    """Show the bytes around the needle and the end of the input; elide long stretches with a note giving
    how many bytes and patches they hold."""
    b = text.encode()
    n = len(b)
    keep = [(max(0, needle_pos - ctx), min(n, needle_pos + 90)), (max(0, n - 140), n)]
    parts, prev = [], 0
    for lo, hi in keep:
        if lo > prev:
            k = sum(1 for x in starts if prev <= x < lo)
            note = "inside one patch" if k == 0 else f"in {k} patch{'es' if k != 1 else ''}"   # k = patch starts in the stretch
            parts.append(f"{{\\rmfamily\\itshape [\\,{lo - prev:,} bytes {note}\\,]}}")
        parts.append(render_span(b, starts, lo, hi))
        prev = hi
    return r"\allowbreak{} ".join(parts)


def write_example(example):
    if example is None:
        return
    q, text, bstarts, pstarts = example
    pos = q["prompt"].encode().find(q["values"][0].encode())
    nb = len(text.encode())
    out = [GEN, r"\begin{figure}[t]", r"\begin{quote}\footnotesize\ttfamily\raggedright\setlength{\emergencystretch}{3em}"]
    for lab, starts in (("BLT", bstarts), ("BPEByte", pstarts)):
        out += [f"\\textbf{{{lab}}} ({len(starts)} patches over {nb:,} bytes):\\\\[1pt]",
                window_render(text, starts, pos) + r"\\[4pt]"]
    out += [r"\end{quote}",
            r"\caption{\hyun{\textbf{An S-NIAH-1 item (" + EXAMPLE_CELL + r") that BLT fails.} Patch starts are in \bb{pink}.}}",
            r"\label{fig:blt_sniah_example}", r"\end{figure}", ""]
    (OVL / "figure_appendix/blt_sniah_example.tex").write_text("\n".join(out))


if __name__ == "__main__":
    main()
