def main():
    D = json.load(open(L / "reports/parse/boundary5_starts.json"))
    for k in D:   # sanity: higher threshold can only remove boundaries
        assert set(D[k]["BLT-t1609"]) <= set(D[k]["BLT-rel"]), k
    files = {"table_appendix/blt_threshold_patch.tex": table_patch(),
             "table_appendix/blt_threshold_sniah.tex": table_sniah(),
             "table_appendix/blt_threshold_downstream.tex": table_downstream(),
             "table_appendix/blt_threshold_robust.tex": table_robust(),
             "figure_appendix/blt_threshold_boundaries.tex": figure_boundaries(),
             "figure_appendix/patch_len_hist_t161.tex": figure_hist()}
    for f, s in files.items():
        (OVL / f).write_text(s)
        print("wrote", f)


if __name__ == "__main__":
    main()
