def load(prefix, name):
    p = BO / f"{prefix}{name}.json"
    if p.exists():
        return json.load(open(p))
    out = {"results": {}}
    for q in sorted(glob.glob(str(BO / f"{prefix}{name}_*.json"))):
        out["results"].update(json.load(open(q))["results"])
    return out


# ---------------------------------------------------------------- patch lengths
PATCH_ROWS = [("DCLM windows", ["dclm/dclm"])] + \
    [(TN[t], [f"downstream/{t}"]) for t in ("hellaswag", "arc_easy", "arc_challenge", "piqa", "winogrande", "boolq", "mmlu_text")] + \
    [(f"S-NIAH-{i}", [f"sniah/sniah{i}"]) for i in (1, 2, 3)] + \
    [("Clean (5-task suite)", [f"downstream/{t}" for t in R5]), ("Noise", [f"noise/{t}" for t in R5]),
     ("Typo", [f"typo/{t}" for t in R5]), ("Despace", [f"despace/{t}" for t in R5])]


def patch_stats(bench, keys):
    c = {}
    for k in keys:
        for Ls, n in bench[k]["hist"].items():
            c[int(Ls)] = c.get(int(Ls), 0) + n
    N = sum(c.values()); B = sum(L * n for L, n in c.items())
    mean = B / N
    sd = (sum(n * (L - mean) ** 2 for L, n in c.items()) / N) ** 0.5
    return mean, sd, c.get(1, 0) / N


def table_patch():
    H = {p: json.load(open(PS / f)) ["benches"] for p, f in HIST.items()}
    out = [GEN, r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}", r"\fitcolumn{%",
           r"\begin{tabular}{lcccc}", r"\toprule",
           r" & \multicolumn{2}{c}{" + TH[0][1] + r"} & \multicolumn{2}{c}{" + TH[1][1] + r"} \\",
           r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
           r"\textbf{Inputs} & B/patch & 1-byte (\%) & B/patch & 1-byte (\%) \\", r"\midrule"]
    for i, (label, keys) in enumerate(PATCH_ROWS):
        if label in ("HellaSwag", "S-NIAH-1", "Clean (5-task suite)"):
            out.append(r"\midrule")
        cells = []
        for p, _ in TH:
            m, sd, one = patch_stats(H[p], keys)
            cells += [f"{m:.2f}\\,{{\\scriptsize$\\pm${sd:.2f}}}", f"{100 * one:.1f}"]
        out.append(f"{label} & " + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", "}",
            r"\caption{\hyun{BLT patch length at the released entropy threshold ($\theta{=}1.34$) and at the "
            r"compression-matched threshold ($\theta{=}1.61$), on the inputs of Table~\ref{tab:patch_stats} "
            r"(mean $\pm$ standard deviation in bytes; \emph{1-byte}: share of single-byte patches). Both use the "
            r"entropy model's $512$-byte sliding window. On the clean inputs of the five downstream tasks behind the "
            r"main-table average, $\theta{=}1.61$ gives $4.65$ bytes per patch, matching the three matched models.}}",
            r"\label{tab:blt_threshold_patch}", r"\end{table}", ""]
    return "\n".join(out)


