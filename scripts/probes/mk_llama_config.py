#!/usr/bin/env python3
"""Emit a llama (subword) baseline config BYTE-MATCHED to the scratchpad arms.

The recorded llama run is byte-matched to the recorded byte-model runs (both ~21 GB of text), so
its 1.0813 BPB cannot be set beside arms trained on 3.15 GB.  This picks a batch and step count
that give llama the SAME number of text bytes as those arms, which is the only way the numbers
belong in one table: BPB is per byte, and a subword model sees the same text in fewer tokens.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hp", required=True)
    ap.add_argument("--run_key", default="llama (subword) · cosine 3.4e-3")
    ap.add_argument("--target_bytes", type=float, required=True,
                    help="text bytes the byte-model arms saw, so llama can be matched to it")
    ap.add_argument("--bytes_per_token", type=float, default=4.8,
                    help="DCLM bytes/token for the llama3 vocab (reports_afterAAAIsub)")
    ap.add_argument("--tag", required=True)
    ap.add_argument("--root", default="/home/hwbae/AUNet_patchlag")
    ap.add_argument("--source", default="dclm_baseline_1.0_2shards_shuffled")
    ap.add_argument("--steps", type=int, default=2000)
    ap.add_argument("--batch_size", type=int, default=4)
    ap.add_argument("--gpus", type=int, default=3)
    ap.add_argument("--outdir", default=str(ROOT / "lingua/apps/main/configs"))
    args = ap.parse_args()

    rec = json.load(open(args.hp))["runs"][args.run_key]
    seq = rec["data"]["seq_len"]
    rec_tok = rec["data"]["batch_size"] * rec["grad_acc_steps"] * \
        rec["distributed"]["dp_replicate"] * seq
    rec_bytes = rec_tok * rec["steps"] * args.bytes_per_token

    # choose grad_acc so that steps x tokens/step x bytes/token == target_bytes
    want_tok = args.target_bytes / args.bytes_per_token / args.steps
    grad_acc = max(1, round(want_tok / (args.batch_size * args.gpus * seq)))
    new_tok = args.batch_size * grad_acc * args.gpus * seq
    got_bytes = new_tok * args.steps * args.bytes_per_token
    lr = round(rec["optim"]["lr"] * (new_tok / rec_tok) ** 0.5, 6)
    warmup = max(1, round(rec["optim"]["warmup"] / rec["steps"] * args.steps))

    name = f"sp_{args.tag}_llama"
    cfg = {
        "name": name,
        "dump_dir": f"{args.root}/runs/scratchpad/{name}",
        "steps": args.steps,
        "grad_acc_steps": grad_acc,
        "seed": rec["seed"],
        "probe_freq": None,
        "optim": {**rec["optim"], "lr": lr, "warmup": warmup},
        "distributed": {**rec["distributed"], "dp_replicate": args.gpus, "dp_shard": 1,
                        "compile": False},
        "model": rec["model"],
        "data": {**rec["data"], "root_dir": f"{args.root}/data",
                 "sources": {args.source: 1.0},
                 "batch_size": args.batch_size,
                 "tokenizer": {"name": "tiktoken",
                               "path": f"{args.root}/tokenizer/llama3/tokenizer.model"}},
        "checkpoint": {"dump": {"every": args.steps, "keep": 1},
                       "eval": {"every": args.steps, "keep": 0}},
        "logging": {"freq": 20},
    }
    p = Path(args.outdir) / f"{name}.yaml"
    p.write_text(
        f"# AUTOGENERATED from {Path(args.hp).name} [{args.run_key}]\n"
        f"# BYTE-MATCHED to the scratchpad arms, not to the recorded llama run:\n"
        f"#   target {args.target_bytes / 1e9:.2f} GB of text -> grad_acc {grad_acc}, "
        f"{args.steps} steps -> {got_bytes / 1e9:.2f} GB\n"
        f"#   (the recorded run saw {rec_bytes / 1e9:.1f} GB at {rec['steps']} steps and reached "
        f"{rec.get('train_BPB')} BPB; that number is NOT comparable to anything here)\n"
        f"#   tokens/step {rec_tok / 1e6:.2f} M -> {new_tok / 1e6:.2f} M "
        f"({args.gpus} GPU), lr {rec['optim']['lr']} -> {lr} (sqrt of the token ratio)\n"
        f"#   bytes/token assumed {args.bytes_per_token} for the llama3 vocab on DCLM\n"
        f"#   compile true -> false, to match how the byte arms were run\n"
        + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
    print(p)
    print(f"  grad_acc={grad_acc}  tokens/step={new_tok / 1e6:.3f}M  "
          f"total={got_bytes / 1e9:.2f} GB (target {args.target_bytes / 1e9:.2f})  lr={lr}")


if __name__ == "__main__":
    main()
