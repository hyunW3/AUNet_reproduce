#!/usr/bin/env python3
"""tab:niah_aunet (main, by answer-to-needle distance, summary.json "tbins") and tab:niah_variants (appendix, by context length) from
reports/niah/needle_variants/summary.json (needle_variants_summary.py). Every row uses the S-NIAH-3 items of the
final set (essay haystack, 0.5k/1k/2k + fit-4k, 250 per length) with only the needle value changed."""
import json, os, sys
from pathlib import Path
L = Path("/mnt/ssd2/hyun2/AUNet"); OVL = Path(os.environ.get("PAPER_DIR", L / "paper_overleaf"))
S = json.load(open(L / "reports/niah/needle_variants/summary.json"))
GEN = "% GENERATED by AUNet/scripts/niah/make_needle_variant_tables.py — edit the script, not this file."
ROWS = [("num7", "7-digit number", "(S-NIAH-2)"), ("uuid", "UUID", "(S-NIAH-3)"), ("uuid_space", "UUID,", "hyphens$\\to$spaces"),
        ("hex32_sp4", "$32$ hex chars,", "space every $4$"), ("digits32", "$32$ random", "digits"),
        ("letters32", "$32$ random", "letters"),
        ("tok4", "BPE-token", "groups ($7{\\times}4$)"), ("rand4", "Random-letter", "groups ($7{\\times}4$)")]
MAIN = ("num7", "uuid", "uuid_space", "hex32_sp4", "digits32", "letters32", "tok4", "rand4")   # tab:niah_aunet rows
OFF = ("uuid_space", "hex32_sp4")                  # kept in tab:niah_aunet as commented-out rows (appendix-only)
NM = {"aunet": "AUNet", "bpebyte": "BPEByte", "llama": "Transformer"}
f2 = lambda x: f"${100 * x:.1f}$"                   # accuracy in %
hy = lambda new, old: new if new == old else r"\hyun{" + new + "}"   # mark cells changed by the tbins switch
allm = lambda s: sum(s["len"].values()) / 4        # mean of the four length means, as tab:sniah_full


DIST = ("<256", "256-512", ">=512")                # tbins: answer-to-needle distance (needle_variants_true_dist.py)
CAP_DIST = (r"Distance is the number of bytes from the start of the needle value to the start of the answer; "
            r"the byte-level encoder and decoder attend over the last $512$ bytes.")


def main_table():
    t = [GEN, r"\begin{table}[!t]", r"\centering",
         r"\caption{\textbf{S-NIAH results by needle value.}",
         r"% Every row differs only the needle value. ",
         r"The ${\geq}$4B is the share of the needle's value bytes in parsing units of at least four bytes.",
         r"\hyun{" + CAP_DIST + "}",
         r"% Appendix~\ref{app:niah_variants} gives the results by context length, including the Transformer.",
         "}", r"\label{tab:niah_aunet}",
         r"\small", r"\setlength{\tabcolsep}{3.5pt}", r"\fitcolumn{%",
         r"\begin{tabular}{llcccccc}", r"\toprule",
         r" &  & & & \multicolumn{4}{c}{\textbf{Acc (\%)} by distance to \hyun{answer}} \\", r"\cmidrule(lr){5-8}",
         r"\textbf{Needle value} & \textbf{Model} & \textbf{B/patch} & \textbf{${\geq}$4B (\%)} & ${<}256$ & $256$--$512$ & ${\geq}512$ & \textbf{All} \\",
         r"\midrule"]
    for j, (k, a, b) in enumerate([r for r in ROWS if r[0] in MAIN]):
        pre = "% " if k in OFF else ""
        if j:
            t.append(r"% \midrule" if k in OFF else r"\midrule")
        for i, m in enumerate(("aunet", "bpebyte")):
            s = S[f"{k}|{m}"]; bn = s["tbins"]
            t.append(pre + f"{(a, b)[i]} & {NM[m]} & ${s['bpp']:.1f}$ & {f2(s['ge4'])} & " +
                     " & ".join(hy(f2(bn[x][0]), f2(s["bins"][x][0])) for x in DIST) + f" & {f2(allm(s))}" + r" \\")
    t += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table}"]
    (OVL / "tables/niah_aunet.tex").write_text("\n".join(t) + "\n")


def app_table():
    t = [GEN, r"\begin{table}[t]", r"\centering",
         r"\caption{\hyun{Needle-value variants of S-NIAH \emph{by context length}. B/patch is the value length divided by the number of parsing units covering it.}}", r"\label{tab:niah_variants}",
         r"\small", r"\setlength{\tabcolsep}{3pt}", r"\fitcolumn{%",
         r"\begin{tabular}{llcccccc}", r"\toprule",
         r" & & & \multicolumn{5}{c}{\textbf{Acc (\%)}} \\", r"\cmidrule(lr){4-8}",
         r"\textbf{Needle value} & \textbf{Model} & \textbf{B/patch} & \textbf{0.5k} & \textbf{1k} & \textbf{2k} & \textbf{4k} & \textbf{Mean} \\",
         r"\midrule"]
    for j, (k, a, b) in enumerate(ROWS):
        if j:
            t.append(r"\midrule")
        for i, m in enumerate(("llama", "aunet", "bpebyte")):
            s = S[f"{k}|{m}"]
            lab = (a, b, "")[i]
            bpp = "--" if m == "llama" else f"${s['bpp']:.2f}$"
            t.append(f"{lab} & {NM[m]} & {bpp} & " + " & ".join(f2(s["len"][x]) for x in ("512", "1024", "2048", "4096")) +
                     f" & {f2(allm(s))} \\\\")
    t += [r"\bottomrule", r"\end{tabular}", "}", r"\end{table}", ""]
    (OVL / "table_appendix/niah_variants.tex").write_text("\n".join(t))


main_table()
if "--app" in sys.argv:                            # tab:niah_variants is hand-edited in the paper; regenerate only on request
    app_table()
print("ok")
