# CI ties: on axes with a 95% CI (tab:main_robust ±), a model within the CI half-width of a
# better model is drawn at the same radius. Groups are formed best-first: the best remaining model
# anchors a group, every model within the anchor's half-width joins it, and the whole group is drawn
# at its mean value (anchoring avoids chaining). Within a group, each model is then moved off the
# group radius by CI_DELTA * (value - mean) / anchor half-width, so tied models stay close but their
# order still shows; a group pushed past the rim / below the LO ring is shifted back as a whole.
# Axes without a CI (PBP, latency, S-NIAH) are unchanged.
CI_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ci_main_table")
CI_KEY = {"Transformer": "llama", "AUNet": "aunet", "BPEByte (ours)": "bpebyte", "BLT": "blt",
          "H-Net": "hnet"}
CI_SRC = {"5-shot": ("downstream5.json", "results", "downstream5_5shot"),
          "Noise": ("ci_both4.json", None, "noise"), "Despace": ("ci_both4.json", None, "despace"),
          "Typo": ("ci_typoleet_both.json", None, "typo")}


def ci_halfwidths(label):
    if label not in CI_SRC:
        return None
    fn, top, key = CI_SRC[label]
    d = json.load(open(os.path.join(CI_DIR, fn)))
    d = (d[top] if top else d)[key]
    return {m: d[k]["half_width"] for m, k in CI_KEY.items() if k in d}


CI_DELTA = 0.04   # radius offset for a deviation of one CI half-width inside a tie group


def ci_groups(raw, hib, hw, keys):
    """[(members, mean, {model: signed deviation in half-widths, + = better})], best group first."""
    vals = {m: raw[m] for m in keys if raw.get(m) is not None}
    order = sorted(vals, key=lambda m: -vals[m] if hib else vals[m])   # best first
    groups = []
    while order:
        a = order[0]
        grp = [m for m in order if abs(vals[m] - vals[a]) <= hw[a]]
        mean = sum(vals[m] for m in grp) / len(grp)
        groups.append((grp, mean, {m: (vals[m] - mean) / hw[a] * (1 if hib else -1) for m in grp}))
        order = [m for m in order if m not in grp]
    return groups


def ci_tie(raw, hib, hw, keys):
    return {m: mean for grp, mean, _ in ci_groups(raw, hib, hw, keys) for m in grp}


def ci_spread(radii, groups):
    """Spread tied models around their shared group radius; keep each group inside [LO, 1]."""
    out = dict(radii)
    for grp, _, dev in groups:
        r = {m: radii[m] + CI_DELTA * dev[m] for m in grp}
        shift = min(0.0, 1.0 - max(r.values())) + max(0.0, LO - min(r.values()))
        out.update({m: r[m] + shift for m in grp})
    return out


def norm(raw, hib, vrange=None, keys=None):
    keys = list(raw) if keys is None else keys
    raw = {m: raw[m] for m in keys if raw.get(m) is not None}   # missing value -> no vertex
    vals = list(raw.values())
    best, worst = (max(vals), min(vals)) if hib else (min(vals), max(vals))
    if vrange is not None:
        lo, hi = vrange
        frac = {m: min(1.0, max(0.0, (raw[m] - lo) / (hi - lo))) for m in raw}
        return {m: LO + (1 - LO) * frac[m] for m in raw}
    if best == worst:
        return {m: 1.0 for m in raw}
    return {m: LO + (1 - LO) * (raw[m] - worst) / (best - worst) for m in raw}


def curved_text(ax, theta_c, r, text, color, fontsize=21):
    """Draw `text` centered on data angle theta_c, each glyph following the
    circle of radius r (letters flip upright when the label sits below the
    horizontal midline). Call only after the figure layout is final."""
    fig = ax.figure
    fig.canvas.draw()   # finalize transforms before measuring
    tr = ax.transData.transform
    x0, y0 = tr((0.0, 0.0))
    px_per_unit = np.hypot(*(tr((0.0, 1.0)) - (x0, y0)))
    fp = FontProperties(size=fontsize, weight="bold")
    px = fig.dpi / 72.0
    widths = []
    for ch in text:
        ext = TextPath((0, 0), ch, prop=fp).get_extents()
        widths.append((ext.width if ext.width > 0 else 0.5 * fontsize) * px)
    kern = 0.10 * fontsize * px
    span = (sum(widths) + kern * (len(text) - 1)) / (r * px_per_unit)
    xc, yc = tr((theta_c, r))
    flip = yc < y0          # lower half: mirror so the label reads upright
    if flip:
        text, widths = text[::-1], widths[::-1]
    t = theta_c - span / 2
    for ch, w in zip(text, widths):
        aw = w / (r * px_per_unit)
        tc = t + aw / 2
        x, y = tr((tc, r))
        rot = np.degrees(np.arctan2(y - y0, x - x0)) - 90 + (180 if flip else 0)
        ax.text(tc, r, ch, rotation=rot, rotation_mode="anchor",
                ha="center", va="center", fontsize=fontsize,
                fontweight="bold", color=color, clip_on=False)
        t += aw + kern / (r * px_per_unit)


def draw(path, paper=False, with_blt=False):
    models = [m for m in COL if with_blt or m != "BLT"]
    scores = {m: [] for m in models}
    axes, groups = [], {}
    for label, hib, raw in AXES:
        hw = ci_halfwidths(label.strip())
        if hw:
            groups[label] = ci_groups(raw, hib, hw, models)
        axes.append((label, hib, ci_tie(raw, hib, hw, models) if hw else raw))
    vranges = {a: perf_range(models, axes) for a in PERF_AXES}
    vranges.update({a: SNIAH_RANGE for a in SNIAH_AXES})
    for label, hib, raw in axes:
        n = norm(raw, hib, vrange=vranges.get(label.strip()), keys=models)
        if label in groups:
            n = ci_spread(n, groups[label])
        for m in models:
            scores[m].append(n.get(m))
    K = len(AXES)
    ang = [2 * pi * i / K for i in range(K)]
    ang_c = ang + ang[:1]
    step = 2 * pi / K

    # fixed layout (tight_layout collapses the polar area once FS=18 labels are added): rim radius
    # R_IN inches, room for labels + arcs around it, legend rows below the Latency label
    R_IN, W_IN, H_IN, CY_IN = 1.85, 7.4, 7.9, 4.3
    side = 2 * R_IN * 1.06   # ylim 1.06 = rim + small margin
    fig = plt.figure(figsize=(W_IN, H_IN))
    ax = fig.add_axes([(W_IN - side) / 2 / W_IN, (CY_IN - side / 2) / H_IN, side / W_IN, side / H_IN],
                      polar=True)
    ax.set_theta_offset(pi / 2 - START_DEG * pi / 180)   # first axis START_DEG clockwise of 12 o'clock
    ax.set_theta_direction(-1)
    for m in models:
        pts = [(a, v) for a, v in zip(ang, scores[m]) if v is not None]   # skip axes without a value
        a_m = [a for a, _ in pts] + [pts[0][0]]
        v = [v for _, v in pts] + [pts[0][1]]
        ax.plot(a_m, v, linestyle=STYLE[m], color=COL[m], lw=LW.get(m, 2), zorder=4 if m in LW else 3,
                label=LEGEND.get(m, m))
        ax.fill(a_m, v, color=COL[m], alpha=0.06, zorder=2)
    ax.set_xticks(ang)
    # labels listed in TICK_OFFSET skip the auto tick placement (a centered two-line label at the
    # lower-right slot would touch the vertex) and are drawn below-right of the rim point instead
    ax.set_xticklabels(["" if a[0] in TICK_OFFSET else TICK_LABEL.get(a[0], a[0]) for a in AXES], fontsize=FS)
    for a_i, (lab, _, _) in zip(ang, AXES):
        if lab in TICK_OFFSET:
            ax.annotate(TICK_LABEL.get(lab, lab), xy=(a_i, 1.0), xytext=TICK_OFFSET[lab], textcoords="offset points",
                        ha="center", va="top", fontsize=FS, annotation_clip=False)
    ax.set_yticks([LO, 0.5, 1.0])
    ax.set_yticklabels([])
    ax.set_ylim(0, 1.06)
    ax.grid(color="#e1e0d9", lw=0.7)
    ax.spines["polar"].set_visible(False)
    ax.tick_params(pad=17)   # 12 until 2026-10-10: with 8 axes the Despace / Decode labels touched their vertices

    # family arcs outside the rim (Performance right, Latency bottom,
    # Robustness left / top)
    for name, i0, i1, c_arc, c_lab in GROUPS:
        t0, t1 = ang[i0] - 0.38 * step, ang[i1] + 0.38 * step
        ts = np.linspace(t0, t1, 80)
        ax.plot(ts, np.full_like(ts, GROUP_R.get(name, (ARC_R,))[0]), color=c_arc, lw=7.5, alpha=0.9,
                solid_capstyle="round", clip_on=False, zorder=1)

    if paper:
        leg = ax.legend(loc="upper left", bbox_to_anchor=(-0.24, 1.16), fontsize=12,
                        frameon=False, handlelength=1.6)
    else:
        # five entries (with BLT) run into the Robustness label: shift up/left
        # with FS=18 no corner is free, so the legend runs in two columns below the Latency label
        leg = ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.43), ncol=3 if with_blt else 2,
                        fontsize=FS, frameon=False, handlelength=2.6, columnspacing=1.2)
        # ax.set_title("1B-scale performance & robustness — higher is better\n"
        #              "(rim = best model per axis; dashed = external reference)", fontsize=9.5, pad=42)
    # curved family labels, drawn last so transforms are final
    for name, i0, i1, _, c_lab in GROUPS:
        t0, t1 = ang[i0] - 0.38 * step, ang[i1] + 0.38 * step
        curved_text(ax, 0.5 * (t0 + t1), GROUP_R.get(name, (0, LAB_R))[1], name, c_lab)
    fig.savefig(path, dpi=180, bbox_inches="tight")
    print("wrote", path)


